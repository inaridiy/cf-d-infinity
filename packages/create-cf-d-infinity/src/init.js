// `init` の本体。まず全部の変更を計画し、衝突がひとつでもあれば何も書かずに終わる。
// 計画が通ってから、まとめてファイルへ書く。2 回目の実行は何も変えない。
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, extname, join, posix, relative } from "node:path";
import { applyEdits, modify, parse } from "jsonc-parser";

export const CLASSES = ["DinfShard", "DinfMeta", "DinfAutoscaler"];
export const DO_BINDINGS = [
  { name: "DINF_SHARD", class_name: "DinfShard" },
  { name: "DINF_META", class_name: "DinfMeta" },
  { name: "DINF_AUTOSCALER", class_name: "DinfAutoscaler" },
];
export const MIGRATION_TAG = "cf-d-infinity-v1";
export const CRON = "* * * * *";
/** 新しいプロジェクトに書く日付。ライブラリのテストが通っている日付に固定する。 */
export const COMPATIBILITY_DATE = "2026-07-01";

/** 利用者の設定と食い違っていて、上書きせずには進めない状態。 */
export class Conflict extends Error {}

const readText = (path) => (existsSync(path) ? readFileSync(path, "utf8") : null);

function parseJsonc(text, path) {
  const errors = [];
  const value = parse(text, errors, { allowTrailingComma: true });
  if (errors.length > 0 || value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new Conflict(`${path} is not valid JSON with comments; fix it and run init again`);
  }
  return value;
}

/** 元のファイルの字下げと改行に合わせる。 */
function formatting(text) {
  const indent = /^([ \t]+)\S/m.exec(text)?.[1] ?? "  ";
  return { insertSpaces: !indent.includes("\t"), tabSize: indent.includes("\t") ? 1 : indent.length, eol: text.includes("\r\n") ? "\r\n" : "\n" };
}

/** コメントと書式を保ったまま JSONC を編集する。 */
class Doc {
  constructor(path, text) {
    this.path = path;
    this.original = text;
    this.text = text;
    this.options = { formattingOptions: formatting(text) };
  }
  get value() {
    return parseJsonc(this.text, this.path);
  }
  set(path, value) {
    this.text = applyEdits(this.text, modify(this.text, path, value, this.options));
  }
  /** 配列の末尾に足す。配列がなければ作る。 */
  push(path, item) {
    const current = path.reduce((v, k) => (v == null ? undefined : v[k]), this.value);
    if (current === undefined) return this.set(path, [item]);
    if (!Array.isArray(current)) throw new Conflict(`${this.path}: "${path.join(".")}" is not an array`);
    this.text = applyEdits(this.text, modify(this.text, [...path, current.length], item, { ...this.options, isArrayInsertion: true }));
  }
  get changed() {
    return this.text !== this.original;
  }
}

const moduleFile = (config) => {
  const main = typeof config.main === "string" ? config.main : "src/index.ts";
  const ext = [".ts", ".tsx", ".mts"].includes(extname(main)) ? ".ts" : ".js";
  return { main, file: posix.join(posix.dirname(main.replaceAll("\\", "/")), `dinf${ext}`) };
};

const moduleSource = `// Generated by create-cf-d-infinity. wrangler.jsonc refers to these classes by name,
// so the Worker's main module has to export them.
export { DinfAutoscaler, DinfDatabase, DinfMeta, DinfShard, autoscale } from "cf-d-infinity/cloudflare";
export { connect } from "cf-d-infinity/client";
`;

/**
 * 既存の Workers プロジェクトへ足す変更を計画する。
 * @returns {{ writes: {path: string, content: string}[], done: string[], kept: string[], next: string[] }}
 */
function planExisting(cwd, configName, opts) {
  const configPath = join(cwd, configName);
  const doc = new Doc(configName, readFileSync(configPath, "utf8"));
  const config = doc.value;
  const done = [];
  const kept = [];
  if (typeof config.name !== "string" || config.name === "") throw new Conflict(`${configName} has no "name"; the Service Binding needs the Worker's name`);

  // Durable Objects
  const bindings = config.durable_objects?.bindings ?? [];
  if (!Array.isArray(bindings)) throw new Conflict(`${configName}: "durable_objects.bindings" is not an array`);
  for (const want of DO_BINDINGS) {
    const have = bindings.find((b) => b?.name === want.name);
    if (have && have.class_name !== want.class_name) {
      throw new Conflict(`${configName}: Durable Object binding ${want.name} already points at ${have.class_name}; cf-d-infinity needs that name`);
    }
    const other = bindings.find((b) => b?.class_name === want.class_name && b?.name !== want.name);
    if (other) throw new Conflict(`${configName}: class ${want.class_name} is already bound as ${other.name}; cf-d-infinity uses that class name`);
    if (have) kept.push(`Durable Object binding ${want.name}`);
    else {
      doc.push(["durable_objects", "bindings"], want);
      done.push(`Durable Object binding ${want.name} -> ${want.class_name}`);
    }
  }

  // Migration
  const migrations = config.migrations ?? [];
  if (!Array.isArray(migrations)) throw new Conflict(`${configName}: "migrations" is not an array`);
  const declared = new Set(migrations.flatMap((m) => [...(m?.new_sqlite_classes ?? []), ...(m?.new_classes ?? [])]));
  const present = CLASSES.filter((c) => declared.has(c));
  if (present.length === CLASSES.length) kept.push("migration for the three classes");
  else if (present.length > 0) {
    throw new Conflict(`${configName}: a migration already declares ${present.join(", ")} but not all of ${CLASSES.join(", ")}`);
  } else {
    if (migrations.some((m) => m?.tag === MIGRATION_TAG)) throw new Conflict(`${configName}: migration tag ${MIGRATION_TAG} is already used for something else`);
    doc.push(["migrations"], { tag: MIGRATION_TAG, new_sqlite_classes: CLASSES });
    done.push(`migration ${MIGRATION_TAG} (SQLite-backed classes ${CLASSES.join(", ")})`);
  }

  // Service Binding
  const services = config.services ?? [];
  if (!Array.isArray(services)) throw new Conflict(`${configName}: "services" is not an array`);
  const service = { binding: opts.binding, service: config.name, entrypoint: "DinfDatabase" };
  const haveService = services.find((s) => s?.binding === opts.binding);
  const everyBinding = [
    ...bindings.map((b) => b?.name), ...Object.keys(config.vars ?? {}),
    ...["kv_namespaces", "d1_databases", "r2_buckets", "queues", "vectorize", "hyperdrive", "analytics_engine_datasets"]
      .flatMap((k) => (Array.isArray(config[k]) ? config[k].map((b) => b?.binding) : [])),
  ];
  if (haveService && (haveService.service !== service.service || haveService.entrypoint !== service.entrypoint)) {
    throw new Conflict(`${configName}: Service Binding ${opts.binding} already points elsewhere; pass --binding <NAME> to use another name`);
  }
  if (!haveService && everyBinding.includes(opts.binding)) {
    throw new Conflict(`${configName}: the name ${opts.binding} is already used by another binding; pass --binding <NAME> to use another name`);
  }
  if (haveService) kept.push(`Service Binding ${opts.binding}`);
  else {
    doc.push(["services"], service);
    done.push(`Service Binding ${opts.binding} -> ${config.name}#DinfDatabase`);
  }

  // Vars
  if (config.vars?.DINF_SHARD_COUNT !== undefined) kept.push(`DINF_SHARD_COUNT = ${config.vars.DINF_SHARD_COUNT}`);
  else {
    doc.set(["vars", "DINF_SHARD_COUNT"], String(opts.shards));
    done.push(`var DINF_SHARD_COUNT = "${opts.shards}" (initial shard count)`);
  }

  // Cron Trigger
  const crons = config.triggers?.crons ?? [];
  if (!Array.isArray(crons)) throw new Conflict(`${configName}: "triggers.crons" is not an array`);
  if (!opts.autoscale) kept.push("no Cron Trigger (--no-autoscale)");
  else if (crons.includes(CRON)) kept.push(`Cron Trigger ${CRON}`);
  else {
    doc.push(["triggers", "crons"], CRON);
    done.push(`Cron Trigger "${CRON}" (wakes the autoscaler once a minute; delete it to turn autoscaling off)`);
  }

  const writes = [];
  if (doc.changed) {
    parseJsonc(doc.text, configName);
    writes.push({ path: configPath, content: doc.text });
  }

  // 再 export するモジュール
  const { main, file } = moduleFile(config);
  const filePath = join(cwd, file);
  const existing = readText(filePath);
  if (existing === null) {
    writes.push({ path: filePath, content: moduleSource });
    done.push(`${file} (re-exports the classes, connect and autoscale)`);
  } else if (existing === moduleSource) kept.push(file);
  else kept.push(`${file} (exists with other content; left as it is)`);

  // main モジュールに DO のクラスを export させる
  const mainPath = join(cwd, main);
  const mainText = readText(mainPath);
  let from = `./${posix.relative(posix.dirname(main.replaceAll("\\", "/")), file).replace(/\.(ts|js)$/, "")}`;
  if (!from.startsWith("./.")) from = from.replace(/^\.\/\.\//, "./");
  const exportLine = `export { DinfAutoscaler, DinfDatabase, DinfMeta, DinfShard } from "${from}";`;
  const next = [];
  if (mainText === null) next.push(`Create ${main} and add this line to it:\n    ${exportLine}`);
  else if (/\bDinfShard\b/.test(mainText)) kept.push(`${main} already exports the classes`);
  else {
    writes.push({ path: mainPath, content: `${mainText}${mainText.endsWith("\n") ? "" : "\n"}\n// Added by create-cf-d-infinity: wrangler.jsonc refers to these classes by name.\n${exportLine}\n` });
    done.push(`${main}: appended one line that re-exports the Durable Object classes`);
  }
  if (opts.autoscale && !(mainText && /\bautoscale\s*\(/.test(mainText))) {
    next.push(`Call the autoscaler from your default export in ${main} (the Cron Trigger invokes it):\n    import { autoscale } from "${from}";\n    export default { /* fetch, ... */ scheduled: (_controller, env) => autoscale(env) };`);
  }

  // package.json
  const pkgPath = join(cwd, "package.json");
  const pkgText = readText(pkgPath);
  if (pkgText === null) next.push(`Install the library: npm install ${opts.packageSpec === opts.defaultSpec ? `cf-d-infinity@${opts.distTag}` : opts.packageSpec}`);
  else {
    const pkg = new Doc("package.json", pkgText);
    const have = pkg.value.dependencies?.["cf-d-infinity"] ?? pkg.value.devDependencies?.["cf-d-infinity"];
    if (have) kept.push(`cf-d-infinity ${have} in package.json`);
    else {
      pkg.set(["dependencies", "cf-d-infinity"], opts.packageSpec);
      writes.push({ path: pkgPath, content: pkg.text });
      done.push(`package.json: dependency cf-d-infinity ${opts.packageSpec}`);
    }
  }
  next.push(`Use it:  import { connect } from "${from}";  const db = connect(env.${opts.binding});`);
  next.push("Then: npm install && npx wrangler dev");
  return { mode: "existing", writes, done, kept, next };
}

/** 空のディレクトリに、DB だけの Worker を作る計画を立てる。 */
function planNew(cwd, opts) {
  const name = (opts.name ?? basename(cwd)).toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "") || "my-db";
  const crons = opts.autoscale ? `\n  // Wakes the autoscaler once a minute. Delete this line and deploy to turn autoscaling off.\n  "triggers": { "crons": ["${CRON}"] },` : "";
  const files = {
    "package.json": `${JSON.stringify({
      name, private: true, type: "module",
      scripts: { dev: "wrangler dev", deploy: "wrangler deploy" },
      dependencies: { "cf-d-infinity": opts.packageSpec },
      devDependencies: { wrangler: "^4.158.0" },
    }, null, 2)}\n`,
    "wrangler.jsonc": `{
  "name": "${name}",
  "main": "src/index.ts",
  "compatibility_date": "${COMPATIBILITY_DATE}",
  // Reachable through Service Bindings only. Set to true to open the Hrana endpoint (wss://, https://)
  // to clients outside Cloudflare; they authenticate with DINF_API_TOKEN.
  "workers_dev": false,
  // DINF_SHARD_COUNT is the number of shards the database starts with.
  "vars": { "DINF_SHARD_COUNT": "${opts.shards}" },${crons}
  "durable_objects": {
    "bindings": [
${DO_BINDINGS.map((b) => `      { "name": "${b.name}", "class_name": "${b.class_name}" }`).join(",\n")}
    ]
  },
  "migrations": [{ "tag": "${MIGRATION_TAG}", "new_sqlite_classes": ${JSON.stringify(CLASSES)} }]
}
`,
    "src/index.ts": `// The database Worker. Other Workers reach it through a Service Binding to the DinfDatabase entrypoint:
//   "services": [{ "binding": "${opts.binding}", "service": "${name}", "entrypoint": "DinfDatabase" }]
// The default export serves the Hrana endpoint for @libsql/client and runs the autoscaler on the Cron Trigger.
export { DinfAutoscaler, DinfDatabase, DinfMeta, DinfShard } from "cf-d-infinity/cloudflare";
export { default } from "cf-d-infinity/cloudflare";
`,
    ".dev.vars": "# Local development only. In production: npx wrangler secret put DINF_API_TOKEN (and DINF_ADMIN_TOKEN).\nDINF_API_TOKEN=dev-only-token\nDINF_ADMIN_TOKEN=dev-only-admin\n",
    ".gitignore": "node_modules/\n.wrangler/\n.dev.vars\n",
  };
  const taken = Object.keys(files).filter((f) => existsSync(join(cwd, f)));
  if (taken.length > 0) {
    throw new Conflict(`No wrangler.jsonc here, so init would create a new database Worker, but these files already exist: ${taken.join(", ")}`);
  }
  return {
    mode: "new",
    writes: Object.entries(files).map(([f, content]) => ({ path: join(cwd, f), content })),
    done: Object.keys(files).map((f) => `${f}`),
    kept: [],
    next: [
      "npm install && npm run dev",
      `Bind it from an application Worker's wrangler.jsonc:\n    "services": [{ "binding": "${opts.binding}", "service": "${name}", "entrypoint": "DinfDatabase" }]`,
      `and use it there:  import { connect } from "cf-d-infinity/client";  const db = connect(env.${opts.binding});`,
    ],
  };
}

/** 変更を計画する。ここでは何も書かない。 */
export function plan(cwd, options = {}) {
  const defaultSpec = `^${options.version ?? "0.1.0-alpha.0"}`;
  const opts = {
    binding: "DINF_DB", shards: 8, autoscale: true, distTag: "alpha", defaultSpec,
    ...options, packageSpec: options.packageSpec ?? defaultSpec,
  };
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(opts.binding)) throw new Conflict(`--binding ${opts.binding} is not a valid binding name`);
  if (!Number.isInteger(opts.shards) || opts.shards < 1 || opts.shards > 4096) throw new Conflict("--shards must be an integer from 1 to 4096");
  const configName = ["wrangler.jsonc", "wrangler.json"].find((f) => existsSync(join(cwd, f)));
  if (configName) return planExisting(cwd, configName, opts);
  if (existsSync(join(cwd, "wrangler.toml"))) {
    throw new Conflict("This project uses wrangler.toml, which init cannot edit. Convert it to wrangler.jsonc, or add the bindings by hand (see the cf-d-infinity README).");
  }
  return planNew(cwd, opts);
}

/** 計画をファイルへ書く。 */
export function apply(result) {
  for (const w of result.writes) {
    mkdirSync(dirname(w.path), { recursive: true });
    writeFileSync(w.path, w.content);
  }
}

export function report(result, cwd) {
  const lines = [];
  const rel = (p) => relative(cwd, p) || p;
  if (result.writes.length === 0) lines.push("Nothing to change: cf-d-infinity is already set up here.");
  else lines.push(result.mode === "new" ? "Created a database Worker:" : "Added cf-d-infinity to this Worker:");
  for (const d of result.done) lines.push(`  + ${d}`);
  for (const k of result.kept) lines.push(`  = ${k} (kept)`);
  if (result.writes.length > 0) lines.push("", `Files written: ${result.writes.map((w) => rel(w.path)).join(", ")}`);
  if (result.next.length > 0) lines.push("", "Next:", ...result.next.map((n) => `  - ${n}`));
  return lines.join("\n");
}
